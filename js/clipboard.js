"use strict";

// Copy / cut / paste of bricks as `topo-clipboard` YAML text (system clipboard, in-memory fallback).
// The pure part (serialize, parse, remap) has no DOM dependency; the rest drives Tools / App.
(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory(require("../vendor/yaml.js"), require("./doc-edit.js"));
  } else {
    root.Clipboard = factory(root.YAML, root.DocEdit);
  }
})(typeof self !== "undefined" ? self : this, function (YAML, DocEdit) {
  const KEY = "topo-clipboard";
  const pick = (obj, names) => names.find((name) => obj[name] !== undefined);
  const isPlain = (v) => v !== null && typeof v === "object" && !Array.isArray(v);

  function serialize(payload) {
    return YAML.stringify({ [KEY]: { version: 1, nodes: payload.nodes || [], links: payload.links || [] } }, { lineWidth: 0 });
  }

  // Returns { nodes, links } or null when the text is not a Topo clipboard.
  function parse(text) {
    let data;
    try {
      data = YAML.parse(String(text));
    } catch (error) {
      return null;
    }
    const body = isPlain(data) ? data[KEY] : null;
    if (!isPlain(body) || !Array.isArray(body.nodes) || !body.nodes.length) return null;
    return { nodes: body.nodes.filter(isPlain), links: Array.isArray(body.links) ? body.links.filter(isPlain) : [] };
  }

  // Pure. options: { taken: Set of ids in use, scheme, parent: local id of the destination or null }.
  // Ids are kept when free, regenerated by the scheme otherwise. Returns { nodes, links, rootIds, idMap }.
  function remap(payload, options) {
    const used = new Set(options.taken || []);
    const scheme = options.scheme || "slug";
    const idMap = new Map();
    const rootIds = [];

    const walk = (node, prefix, parent) => {
      const copy = JSON.parse(JSON.stringify(node));
      const raw = String(node.id === undefined || node.id === null ? "" : node.id).trim();
      const local = raw ? raw.split(".").pop() : "";
      const path = prefix ? `${prefix}.${local}` : local;
      const labelKey = pick(node, ["label", "titre", "title"]);
      let id = local;

      if (!id || used.has(id)) {
        id = DocEdit.autoId(scheme, { label: labelKey ? node[labelKey] : local, type: node.type, parent }, used);
      }
      used.add(id);
      idMap.set(path, id);
      copy.id = id;

      const kidsKey = pick(node, ["children", "enfants"]);
      if (kidsKey && Array.isArray(node[kidsKey])) {
        copy[kidsKey] = node[kidsKey].filter(isPlain).map((child) => walk(child, path, id));
      }
      return copy;
    };

    const nodes = (payload.nodes || []).map((node) => {
      const copy = walk(node, "", options.parent || null);
      rootIds.push(copy.id);
      return copy;
    });

    const links = [];
    (payload.links || []).forEach((link) => {
      const fromKey = pick(link, ["from", "de"]);
      const toKey = pick(link, ["to", "vers"]);
      const from = fromKey && idMap.get(String(link[fromKey]));
      const to = toKey && idMap.get(String(link[toKey]));
      if (!from || !to) return;
      const copy = JSON.parse(JSON.stringify(link));
      copy[fromKey] = from;
      copy[toKey] = to;
      links.push(copy);
    });

    return { nodes, links, rootIds, idMap };
  }

  const api = { KEY, serialize, parse, remap, memory: null };

  // ---------- browser side ----------

  api.targetIds = function targetIds(ids) {
    const picked = ids && ids.length ? ids : Tools.selection().nodes;
    if (picked.length) return picked;
    return Graph.selectedId ? [Graph.selectedId] : [];
  };

  api.write = async function write(text) {
    this.memory = text;
    try {
      await navigator.clipboard.writeText(text);
    } catch (error) { /* refused: the in-memory copy still serves this page */ }
  };

  api.read = async function read() {
    try {
      const text = await navigator.clipboard.readText();
      if (parse(text)) return text;
    } catch (error) { /* refused or unavailable */ }
    return this.memory;
  };

  api.copy = async function copy(ids) {
    // Only links selected (no brick): copy the link style as a preset of the Link tool.
    if (!(ids && ids.length)) {
      const picked = Tools.selection();
      if (!picked.nodes.length && picked.edges.length) return Tools.copyLinkStyle(picked.edges);
    }
    const targets = this.targetIds(ids);
    if (!targets.length) return false;
    const payload = DocEdit.exportNodes(App.getText(), targets);
    await this.write(serialize(payload));
    const count = payload.nodes.length;
    App.showMessage(`${count} brique(s) copiée(s)${payload.links.length ? ` avec ${payload.links.length} lien(s)` : ""}.`, "success");
    return true;
  };

  api.cut = async function cut(ids) {
    const targets = this.targetIds(ids);
    if (!targets.length || !(await this.copy(targets))) return;
    const plan = Tools.deletionPlan(targets, []);
    if (plan.roots.length) Tools.applyDelete(plan, Boolean(Settings.get(Tools.DELETE_KEY)));
  };

  api.paste = async function paste(destinationId) {
    const payload = parse(await this.read());
    if (!payload) {
      App.showMessage("Le presse-papiers ne contient pas de briques Topo.", "warning");
      return false;
    }

    const model = App.getModel();
    const selected = Tools.selection().nodes;
    const parentId = destinationId !== undefined ? destinationId : selected.length === 1 ? selected[0] : null;
    const parent = parentId && model.byId.has(parentId) ? model.byId.get(parentId) : null;
    const mapped = remap(payload, {
      taken: Forms.takenIds(model),
      scheme: Settings.get("ids.scheme"),
      parent: parent ? parent.localId : null
    });
    const where = parent ? `dans « ${parent.label} »` : "à la racine";
    const wasCollapsed = Boolean(parent) && App.collapsed.has(parent.id);

    if (parent) App.collapsed.delete(parent.id);

    const done = await App.edit(`Collage de ${mapped.nodes.length} brique(s) ${where}`, (text) => {
      let next = text;
      mapped.nodes.forEach((node) => { next = DocEdit.addNode(next, parent ? parent.id : null, node); });
      mapped.links.forEach((link) => { next = DocEdit.addLink(next, link); });
      return next;
    });

    if (!done) {
      if (wasCollapsed) App.collapsed.add(parent.id);
      return false;
    }

    const point = destinationId !== undefined ? Tools.menuPoint : null;

    if (!(point && Tools.placeAtPoint(mapped.rootIds, point))) Tools.placeBricks(mapped.rootIds);
    Repulsion.settle(mapped.rootIds, { newIds: mapped.rootIds });
    Tools.selectIds(mapped.rootIds);
    App.showMessage(`${mapped.nodes.length} brique(s) collée(s) ${where}.`, "success");
    return true;
  };

  return api;
});
