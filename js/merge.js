"use strict";

(function (root, factory) {
  if (typeof module === "object" && module.exports) {
    module.exports = factory(require("./schema.js"), require("./model.js"), (() => { try { return require("js-yaml"); } catch (e) { return require("../vendor/js-yaml.js"); } })());
  } else {
    root.Merge = factory(root.Schema, root.Model, root.jsyaml);
  }
})(typeof self !== "undefined" ? self : this, function (Schema, Model, jsyaml) {
  const HEADER = "# Generated by topo — do not edit by hand, edit the brick files\n";
  const isObj = (v) => v && typeof v === "object" && !Array.isArray(v);
  const str = (v) => (v === undefined || v === null ? "" : String(v).trim());
  const join = (parent, id) => (parent ? `${parent}.${id}` : id);

  function isBrickFile(path) {
    const segs = String(path).replace(/\\/g, "/").split("/");
    const name = segs[segs.length - 1];
    if (!/^(brick|.+\.brick)\.ya?ml$/.test(name)) return false;
    return !segs.slice(0, -1).some((s) => s === "node_modules" || s.startsWith("."));
  }

  // Normalizes a brick file: node fields + inner nodes + links.
  function readBrick(raw) {
    const r = isObj(raw) ? raw : {};
    const own = Schema.normalizeNode(r);
    const inner = Schema.normalize({ nodes: r.nodes !== undefined ? r.nodes : r.noeuds }).nodes || own.children || [];
    const links = Schema.normalize({ links: r.links !== undefined ? r.links : r.liens }).links || [];
    return { id: str(r.id), label: own.label, type: own.type, role: own.role, meta: own.meta || {}, inner, links, style: Schema.normalize(r).style, view: Schema.normalize(r).view, settings: r.settings, trash: r.trash };
  }

  function newDir(name, segs) {
    return { name, segs, brick: null, fileBricks: [], dirs: new Map() };
  }

  function getDir(root, segs) {
    let cur = root;
    segs.forEach((s, i) => {
      if (!cur.dirs.has(s)) cur.dirs.set(s, newDir(s, segs.slice(0, i + 1)));
      cur = cur.dirs.get(s);
    });
    return cur;
  }

  function loadBricks(files, output, anomalies) {
    const root = newDir("", []);
    const sorted = files.filter((f) => f.path !== output && isBrickFile(f.path)).sort((a, b) => a.path.localeCompare(b.path));
    sorted.forEach((f) => {
      let raw;
      try {
        raw = jsyaml.load(f.text);
      } catch (e) {
        anomalies.push({ level: "error", code: "yaml-error", message: `YAML invalide dans ${f.path} : ${e.message.split("\n")[0]}`, file: f.path });
        return;
      }
      const segs = f.path.replace(/\\/g, "/").split("/");
      const name = segs.pop();
      const entry = { path: f.path, ...readBrick(raw) };
      const dir = getDir(root, segs);
      if (/^brick\./.test(name)) dir.brick = entry;
      else dir.fileBricks.push({ ...entry, fallbackId: name.replace(/\.brick\.ya?ml$/, "") });
    });
    return root;
  }

  function createBuilder(anomalies) {
    const registry = new Map();
    const bricks = [];
    let auto = 0;

    const register = (q, localId, parentQ, file) => {
      if (registry.has(q)) {
        anomalies.push({ level: "error", code: "duplicate-id", message: `L’identifiant qualifié « ${q} » est défini plusieurs fois.`, ref: q, file });
        return false;
      }
      registry.set(q, { id: q, qualifiedId: q, localId, parent: parentQ });
      return true;
    };

    const withSource = (meta, path, localId) => ({ ...meta, source: path, sourceId: localId });

    const innerNodes = (list, parentQ, path) => {
      const out = [];
      list.forEach((n) => {
        let id = str(n.id);
        if (!id) {
          auto += 1;
          id = `node-${auto}`;
          anomalies.push({ level: "warning", code: "missing-id", message: `Nœud sans « id » dans ${path} : « ${id} » attribué.`, file: path });
        }
        const q = join(parentQ, id);
        if (!register(q, id, parentQ, path)) return;
        const node = { id: q, label: n.label || id };
        if (n.type !== undefined) node.type = n.type;
        if (n.role !== undefined) node.role = n.role;
        node.meta = withSource(n.meta || {}, path, id);
        if (n.children && n.children.length) node.children = innerNodes(n.children, q, path);
        out.push(node);
      });
      return out;
    };

    const brickNode = (entry, id, parentQ, extra) => {
      const q = join(parentQ, id);
      if (!register(q, id, parentQ, entry ? entry.path : null)) return null;
      const children = [...(entry ? innerNodes(entry.inner, q, entry.path) : []), ...extra(q)];
      const node = { id: q, label: (entry && entry.label) || id };
      const type = entry && entry.type !== undefined ? entry.type : children.length ? "group" : undefined;
      if (type !== undefined) node.type = type;
      if (entry && entry.role !== undefined) node.role = entry.role;
      if (entry) node.meta = withSource(entry.meta, entry.path, id);
      if (children.length) node.children = children;
      if (entry && entry.links.length) bricks.push({ entry, ctx: q });
      return node;
    };

    const dirChildren = (dir, parentQ) => {
      const out = [];
      dir.fileBricks.forEach((fb) => {
        const n = brickNode(fb, fb.id || fb.fallbackId, parentQ, () => []);
        if (n) out.push(n);
      });
      [...dir.dirs.values()].sort((a, b) => a.name.localeCompare(b.name)).forEach((sub) => {
        const id = (sub.brick && sub.brick.id) || sub.name;
        const n = brickNode(sub.brick, id, parentQ, (q) => dirChildren(sub, q));
        if (n) out.push(n);
      });
      return out;
    };

    return { registry, bricks, innerNodes, dirChildren };
  }

  function resolveLinks(builder, anomalies) {
    const nodes = [...builder.registry.values()];
    const model = { nodes, byId: builder.registry };
    const links = [];
    builder.bricks.forEach(({ entry, ctx }) => {
      entry.links.forEach((l, i) => resolveOne(l, i, entry.path, ctx || null));
    });
    return links;

    function resolveOne(l, i, file, ctx) {
      const from = str(l.from);
      const to = str(l.to);
      const path = `links[${i}]`;
      if (!from || !to) {
        anomalies.push({ level: "error", code: "unknown-ref", message: `Lien n°${i + 1} de ${file} : « from » et « to » sont requis.`, file, path });
        return;
      }
      const rf = Model.resolveRef(from, model, ctx);
      const rt = Model.resolveRef(to, model, ctx);
      const bad = [["from", from, rf], ["to", to, rt]].filter((b) => b[2].error);
      bad.forEach(([key, ref, res]) => {
        const p = Model.refProblem(key, ref, res, rf.id || from, rt.id || to);
        const fixes = p.fixes.map((f) => ({ file, ...f }));
        anomalies.push({ level: "error", code: p.code, message: p.message, file, path, ref, candidates: p.candidates, fixes, fix: fixes[0] });
      });
      if (bad.length) return;
      if (rf.id === rt.id) {
        anomalies.push({ level: "warning", code: "self-link", message: `Lien de ${file} : « ${from} » relié à lui-même, ignoré.`, file, path });
        return;
      }
      const link = { from: rf.id, to: rt.id };
      if (l.label !== undefined) link.label = l.label;
      link.meta = { ...(l.meta || {}), source: file };
      links.push(link);
    }
  }

  function mergeProject(files, options) {
    const output = (options && options.output) || "architecture.yaml";
    const anomalies = [];
    const root = loadBricks(files, output, anomalies);
    const builder = createBuilder(anomalies);
    const rootBrick = root.brick;
    const top = [
      ...(rootBrick ? builder.innerNodes(rootBrick.inner, "", rootBrick.path) : []),
      ...builder.dirChildren(root, "")
    ];
    if (rootBrick && rootBrick.links.length) builder.bricks.push({ entry: rootBrick, ctx: null });

    const document = { title: (rootBrick && rootBrick.label) || "Architecture", nodes: top, links: resolveLinks(builder, anomalies) };
    if (rootBrick && rootBrick.style) document.style = rootBrick.style;
    // Document-level blocks written by the app into the root brick survive rebuilds.
    ["view", "settings", "trash"].forEach((key) => {
      if (rootBrick && rootBrick[key]) document[key] = rootBrick[key];
    });
    return { document, anomalies };
  }

  function applyFix(text, fix) {
    const aliases = { from: ["from", "de"], to: ["to", "vers"] };
    const keys = (aliases[fix.key] || [fix.key]).join("|");
    const old = String(fix.oldRef).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp(`((?:^|[\\s{,])(?:${keys})\\s*:\\s*)(["']?)${old}\\2(?=\\s*(?:[,}#]|\\r?$))`, "g");
    return String(text)
      .split("\n")
      .map((line) => line.replace(re, (_, head, q) => `${head}${q}${fix.newRef}${q}`))
      .join("\n");
  }

  function toYaml(document) {
    return HEADER + jsyaml.dump(document, { lineWidth: -1, noRefs: true });
  }

  return { isBrickFile, mergeProject, applyFix, toYaml };
});
